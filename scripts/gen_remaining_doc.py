#!/usr/bin/env python3
"""Write docs/RECOLLECTION_REMAINING.md: what is still owed, and on what.

Generated from recollection_list.csv and the registry so the cell lists and the
GPU counts are the real ones. A_camera_ready devices already re-collected
(A100-SXM4-80GB, RTX 4050) are reported as done rather than dropped, so the
list stays a complete account of the 46 unusable jobs.
"""
import os
import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from workloads.registry import WORKLOAD_REGISTRY as R  # noqa: E402

DONE = {
    "A100-SXM4-80GB": "re-collected 2026-10-23 (aborted cells) and 2026-10-26 "
                      "(starved cells as `_mw8`); all runs healthy",
    "GeForce RTX 4050 Laptop GPU": "re-collected 2026-10-27 on the laptop; "
                                   "all 27 runs healthy",
}
# What a provider has to give you, per GPU model.
HW_NOTE = {
    "B200": "NVIDIA B200 (Blackwell, 180GB). GCP sells it only as 8-GPU "
            "a4-highgpu-8g, which is why it is blocked here; a 1xB200 instance "
            "elsewhere is enough for every job below.",
    "H200": "NVIDIA H200 141GB (`H200` in `nvidia-smi`). A 1xH200 instance is "
            "enough; GCP again only offers 8-GPU a3-ultragpu-8g.",
    "H100 NVL": "NVIDIA **H100 NVL** (94GB PCIe) specifically -- NOT H100 SXM "
                "80GB, which reports a different `gpu_name` and would land in "
                "the corpus as a different device.",
}


def gpus_for(cell):
    """GPU count from the registry command: torchrun --nproc_per_node=N, else 1."""
    e = R.get(cell)
    if not e:
        return None
    for tok in (str(x) for x in e["command"]):
        m = re.match(r"--nproc_per_node=(\d+)$", tok)
        if m:
            return int(m[1])
    return 1


def command_for(cell):
    e = R.get(cell)
    if not e:
        return None
    args = [str(x) for x in e["command"]
            if not str(x).endswith("python") and "python" not in os.path.basename(str(x))]
    args = [os.path.basename(a) if a.endswith(".py") else a for a in args]
    return " ".join(args)


def main():
    d = pd.read_csv(ROOT / "docs/camera_ready_results_20261022/recollection_list.csv")
    # A starved cell must be collected as its worker-fed sibling: re-running the
    # original command reproduces the starvation.
    d["collect_as"] = d.apply(
        lambda r: r.cell + "_mw8" if r.verdict == "starved" else r.cell, axis=1)
    d["gpus"] = d.collect_as.map(gpus_for)

    out = ["# Re-collection still owed\n",
           "Generated by `scripts/gen_remaining_doc.py` from "
           "`camera_ready_results_20261022/recollection_list.csv`. "
           "%d tier-A adversarial jobs are unusable; this is all of them, "
           "including the ones already redone.\n" % len(d),
           "Every job below is **single-GPU**. None of the remaining cells is a "
           "`torchrun` job, so no multi-GPU instance is needed anywhere -- the "
           "only reason GCP cannot run B200 and H200 is that it sells them "
           "exclusively in 8-GPU nodes.\n",
           "Three reps per cell throughout. Always pass "
           "`--require-gpu-activity`: every one of these jobs was produced "
           "by a run that exited cleanly.\n"]

    todo = d[~d.hw.isin(DONE)]
    done = d[d.hw.isin(DONE)]

    out.append("## Summary\n")
    out.append("| GPU model | GPUs per job | cells | runs (x3) | approx time |")
    out.append("| :-- | --: | --: | --: | --: |")
    for hw, g in todo.groupby("hw"):
        cells = sorted(set(g.collect_as))
        secs = sum(float(g[g.collect_as.eq(c)].duration_s.iloc[0]) for c in cells) * 3
        out.append(f"| `{hw}` | 1 | {len(cells)} | {len(cells) * 3} | "
                   f"{secs / 3600:.1f} h |")
    tot_runs = sum(len(set(g.collect_as)) * 3 for _, g in todo.groupby("hw"))
    tot_hours = sum(sum(float(g[g.collect_as.eq(c)].duration_s.iloc[0])
                        for c in set(g.collect_as)) * 3
                    for _, g in todo.groupby("hw")) / 3600
    out.append(f"| **total** | | | **{tot_runs}** | **{tot_hours:.1f} h** |")
    out.append("")

    for hw, g in todo.groupby("hw"):
        cells = sorted(set(g.collect_as))
        out.append(f"## {hw}\n")
        if hw in HW_NOTE:
            out.append(HW_NOTE[hw] + "\n")
        counts = g.verdict.value_counts().to_dict()
        out.append("Why: " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + ".\n")
        out.append("| cell to collect | GPUs | duration | replaces | because |")
        out.append("| :-- | --: | --: | :-- | :-- |")
        for c in cells:
            row = g[g.collect_as.eq(c)].iloc[0]
            why = {"aborted": f"ran {row.span_s:.0f}s of {row.duration_s:.0f}s, GPU never active",
                   "starved": f"ran full length, GPU busy {row.busy:.1%} of samples",
                   "truncated": f"ran {row.span_s:.0f}s of {row.duration_s:.0f}s, GPU was working"}[row.verdict]
            gpus = "**not in registry**" if pd.isna(row.gpus) else f"{int(row.gpus)}"
            out.append(f"| `{c}` | {gpus} | {row.duration_s:.0f}s | "
                       f"`{row.cell}` | {why} |")
        out.append("")
        runnable = [c for c in cells if gpus_for(c) is not None]
        skipped = [c for c in cells if gpus_for(c) is None]
        if skipped:
            out.append(f"`{'`, `'.join(skipped)}` {'is' if len(skipped) == 1 else 'are'} "
                       f"**not in the registry**, so there is no command to "
                       f"reproduce {'it' if len(skipped) == 1 else 'them'}. "
                       f"Left out of the loop below rather than guessed at; "
                       f"between them they carry "
                       f"{int(g[g.collect_as.isin(skipped)].windows.sum())} windows.\n")
        out.append("```bash")
        out.append(f'CELLS="{" ".join(runnable)}"')
        out.append("for cell in $CELLS; do for rep in 1 2 3; do")
        out.append('  log="logs/${STAMP}__$(hostname -s)__${cell#adversarial_}_rep${rep}.log"')
        out.append('  grep -q "SPAR_CELL_DONE.*exit=0" "$log" 2>/dev/null && continue')
        out.append('  python scripts/run_workload.py --workload "$cell" \\')
        out.append('    --output-dir data/ --no-dcgm --require-gpu-activity 2>&1 | tee "$log"')
        out.append("done; done")
        out.append("```\n")

    out.append("## Already re-collected\n")
    for hw, note in DONE.items():
        n = len(set(done[done.hw.eq(hw)].collect_as))
        out.append(f"- **{hw}** -- {n} cells. {note}.")
    out.append("")
    out.append("## Why the starved cells change name\n")
    out.append("`adversarial_L_diluted_*` and `adversarial_K_online_learning` are "
               "listed as `_mw8`. Re-running the original command reproduces the "
               "starvation -- `num_workers=0` puts `Resize(224)` on one CPU thread "
               "and the GPU waits, which is how the archived runs managed four "
               "batches in 324 s. The `_mw8` cells pass `--num-workers 8` and are "
               "GPU-bound. That makes them a different workload, so they carry a "
               "different label and must not be pooled with the originals, which "
               "stay in the registry as what the camera-ready measured.\n")
    (ROOT / "docs/RECOLLECTION_REMAINING.md").write_text("\n".join(out) + "\n")
    print("wrote docs/RECOLLECTION_REMAINING.md")
    print(todo.groupby("hw").apply(
        lambda g: pd.Series({"cells": len(set(g.collect_as)),
                             "gpus_per_job": sorted(set(g.gpus.dropna())),
                             "runs": len(set(g.collect_as)) * 3}),
        include_groups=False).to_string())


if __name__ == "__main__":
    raise SystemExit(main())
